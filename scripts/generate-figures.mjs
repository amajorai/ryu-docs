/*
 * Writes the docs-home figures to public/figures/<name>-<theme>.svg, and every
 * article figure in scripts/figures/docs/<name>.mjs to
 * public/figures/docs/<name>-<theme>.svg plus their sizes to
 * src/components/mdx/docs-figures.generated.ts (read by the MDX <Figure>).
 *
 * Each figure is an Anatomy-style isometric drawing (scripts/figures/, built
 * with the vendored kit) without the card text: no figure number, title, hint,
 * readout or caption. The SVGs are standalone, with the kit's styles embedded
 * and the paper colour matched to the page background they sit on.
 * Run with `bun run generate:figures`; `--check` fails when a file is stale.
 */

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import {
  HEIGHT as DOCK_H,
  WIDTH as DOCK_W,
  dockFigure,
} from "./figures/dock.mjs";
import {
  HEIGHT as RACK_H,
  WIDTH as RACK_W,
  rackFigure,
} from "./figures/rack.mjs";
import { renderFigure } from "./figures/render.mjs";
import {
  HEIGHT as YARD_H,
  WIDTH as YARD_W,
  yardFigure,
} from "./figures/yard.mjs";

const SCRIPTS = dirname(fileURLToPath(import.meta.url));
const OUT = join(SCRIPTS, "../public/figures");
const DOCS_SOURCES = join(SCRIPTS, "figures/docs");
const SIZES = join(SCRIPTS, "../src/components/mdx/docs-figures.generated.ts");

const FIGURES = [
  { name: "dock", build: dockFigure, width: DOCK_W, height: DOCK_H },
  { name: "yard", build: yardFigure, width: YARD_W, height: YARD_H },
  { name: "rack", build: rackFigure, width: RACK_W, height: RACK_H },
];

// Article figures: each module exports WIDTH, HEIGHT and figure() -> {label, body}.
const docsFigures = [];
for (const file of readdirSync(DOCS_SOURCES).sort()) {
  if (!file.endsWith(".mjs")) {
    continue;
  }
  const module = await import(pathToFileURL(join(DOCS_SOURCES, file)).href);
  docsFigures.push({
    name: `docs/${file.slice(0, -".mjs".length)}`,
    build: module.figure,
    width: module.WIDTH,
    height: module.HEIGHT,
  });
}

const check = process.argv.includes("--check");
let stale = 0;
mkdirSync(join(OUT, "docs"), { recursive: true });

/** Write `content` to `file`, or under --check count it stale when it differs. */
function emit(file, content, shown) {
  if (!check) {
    writeFileSync(file, content);
    return;
  }
  let current = "";
  try {
    current = readFileSync(file, "utf8");
  } catch {
    // A missing file is stale.
  }
  if (current !== content) {
    stale += 1;
    console.error(`stale: ${shown}`);
  }
}

for (const figure of [...FIGURES, ...docsFigures]) {
  for (const theme of ["light", "dark"]) {
    const svg = renderFigure(figure, theme);
    emit(
      join(OUT, `${figure.name}-${theme}.svg`),
      `${svg}\n`,
      `public/figures/${figure.name}-${theme}.svg`,
    );
  }
}

// Quote only keys that are not identifiers, as the formatter would.
const key = (name) => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : `"${name}"`);
const sizes = docsFigures.map(
  ({ name, width, height }) =>
    `  ${key(name.slice("docs/".length))}: { width: ${width}, height: ${height} },\n`,
);
emit(
  SIZES,
  [
    "// Generated by scripts/generate-figures.mjs. Do not edit.\n\n",
    "type FigureSize = { height: number; width: number };\n\n",
    `export const DOCS_FIGURES: Record<string, FigureSize> = {${sizes.length ? `\n${sizes.join("")}` : ""}};\n`,
  ].join(""),
  "src/components/mdx/docs-figures.generated.ts",
);

if (stale > 0) {
  console.error("Run `bun run generate:figures` to refresh the figures.");
  process.exit(1);
}
