/** Generated outputs: catalog index, meta, preview registries, and docs writing. */
import { execFileSync } from "node:child_process";
import {
  closeSync,
  mkdtempSync,
  openSync,
  readFileSync,
  rmSync,
} from "node:fs";
import { mkdir, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import * as path from "node:path";
import { fileURLToPath } from "node:url";

import { buildUiCatalog } from "./catalog.ts";
import { componentNavigationPages, componentPage } from "./component-page.ts";
import {
  COMPONENTS_ROOT,
  PREVIEW_METADATA_SOURCE,
  PREVIEW_MODULES_SOURCE,
  type UiComponent,
  writeGeneratedFile,
} from "./shared.ts";

function componentsIndex(catalog: UiComponent[]): string {
  const lines = [
    "---",
    'title: "Components"',
    'description: "The component catalog for @ryu/ui, with one reference page for every documented source module."',
    "---",
    "",
    "Every entry below maps to a real `@ryu/ui` component module. Open a component page for its live preview, variants, settings, import path, named exports, and usage example.",
    "",
    "Use the [Ryu UI overview](/docs/ui), [UI getting started](/docs/ui/getting-started), and [primitive usage guide](/docs/ui/primitives) to place these components in a host surface.",
    "",
  ];
  let currentCategory = "";
  for (const [index, component] of catalog.entries()) {
    if (component.category !== currentCategory) {
      currentCategory = component.category;
      lines.push(`## ${currentCategory}`, "", "<Cards>");
    }
    lines.push(
      `  <DocCard href="/docs/ui/components/${component.pageSlug}" title=${JSON.stringify(component.title)} description={${JSON.stringify(component.description)}} />`,
    );
    const next = catalog[index + 1];
    if (!next || next.category !== currentCategory) {
      lines.push("</Cards>", "");
    }
  }
  return `${lines.join("\n")}\n`;
}

function componentsMeta(catalog: UiComponent[]): string {
  return `${JSON.stringify(
    {
      title: "Components",
      description: "The @ryu/ui component catalog.",
      pages: componentNavigationPages(catalog),
    },
    null,
    2,
  )}\n`;
}

export function previewModulesSource(catalog: UiComponent[]): string {
  const lines = [
    "// This file is generated by apps/fumadocs/scripts/generate-ui-docs.ts.",
    "// Keep the import paths aligned with the @ryu/ui package export map.",
    "",
    "export const UI_COMPONENT_MODULE_LOADERS = {",
  ];
  for (const component of catalog) {
    const packageImport = `@ryu/ui/${component.importPath}`;
    const entry = `  ${JSON.stringify(component.importPath)}: async () => import(${JSON.stringify(packageImport)}),`;
    if (entry.length <= 80) {
      lines.push(entry);
    } else {
      lines.push(
        `  ${JSON.stringify(component.importPath)}: async () =>`,
        `    import(${JSON.stringify(packageImport)}),`,
      );
    }
  }
  lines.push(
    "};",
    "",
    "export type UiComponentImportPath = keyof typeof UI_COMPONENT_MODULE_LOADERS;",
    "",
    "function isUiComponentImportPath(",
    "  component: string,",
    "): component is UiComponentImportPath {",
    "  return Object.hasOwn(UI_COMPONENT_MODULE_LOADERS, component);",
    "}",
    "",
    "export function getUiComponentModuleLoader(component: string) {",
    "  return isUiComponentImportPath(component)",
    "    ? UI_COMPONENT_MODULE_LOADERS[component]",
    "    : undefined;",
    "}",
  );
  return `${lines.join("\n")}\n`;
}
/** Refresh only the lazy import registry; full docs generation uses the same source. */
export async function generateUiPreviewModules(): Promise<UiComponent[]> {
  const catalog = await buildUiCatalog();
  await writeGeneratedFile(
    PREVIEW_MODULES_SOURCE,
    previewModulesSource(catalog),
  );
  return catalog;
}

export function previewMetadataSource(catalog: UiComponent[]): string {
  const lines = [
    "// This file is generated by apps/fumadocs/scripts/generate-ui-docs.ts.",
    "// It contains only literal public prop options used by the docs playground.",
    "",
    "export type UiComponentPreviewMetadata = {",
    "  props: Record<string, string[]>;",
    "  targetExport: string;",
    "};",
    "",
    "export const UI_COMPONENT_PREVIEW_METADATA = {",
  ];

  for (const component of catalog) {
    lines.push(
      `  ${JSON.stringify(component.importPath)}: ${JSON.stringify(component.preview)},`,
    );
  }

  lines.push(
    "} satisfies Record<string, UiComponentPreviewMetadata>;",
    "",
    "export function getUiComponentPreviewMetadata(component: string): UiComponentPreviewMetadata | undefined {",
    "  return isUiComponentPreviewPath(component) ? UI_COMPONENT_PREVIEW_METADATA[component] : undefined;",
    "}",
    "",
    "function isUiComponentPreviewPath(component: string): component is keyof typeof UI_COMPONENT_PREVIEW_METADATA {",
    "  return Object.hasOwn(UI_COMPONENT_PREVIEW_METADATA, component);",
    "}",
  );
  // Use the docs app's declared formatter so regeneration also reproduces its checked-in style.
  // A regular stdout file avoids nonblocking pipe writes in the native formatter.
  const outputDirectory = mkdtempSync(path.join(tmpdir(), "ryu-ui-metadata-"));
  const outputPath = path.join(outputDirectory, "formatted.ts");
  try {
    const outputDescriptor = openSync(outputPath, "w");
    try {
      execFileSync(
        process.execPath,
        [
          fileURLToPath(import.meta.resolve("@biomejs/biome/bin/biome")),
          "format",
          `--stdin-file-path=${PREVIEW_METADATA_SOURCE}`,
        ],
        {
          cwd: path.resolve(import.meta.dir, "../.."),
          input: `${lines.join("\n")}\n`,
          encoding: "utf8",
          stdio: ["pipe", outputDescriptor, "pipe"],
        },
      );
    } catch (error) {
      // Keep the original child-process error and its partial formatted stdout.
      if (error instanceof Error) {
        Object.assign(error, { stdout: readFileSync(outputPath, "utf8") });
      }
      throw error;
    } finally {
      closeSync(outputDescriptor);
    }
    return readFileSync(outputPath, "utf8");
  } finally {
    rmSync(outputDirectory, { recursive: true, force: true });
  }
}

export type UiDocsPage = {
  /** File name relative to `content/docs/ui/components`. */
  fileName: string;
  content: string;
};

/**
 * Render every file the generator owns under `content/docs/ui/components`.
 * `generateUiDocs` writes exactly these files, so checked-in pages can be
 * compared with the generator output without touching the content tree.
 */
export function renderUiDocsPages(catalog: UiComponent[]): UiDocsPage[] {
  const pages: UiDocsPage[] = [
    { fileName: "meta.json", content: componentsMeta(catalog) },
    { fileName: "index.mdx", content: componentsIndex(catalog) },
  ];
  for (const component of catalog) {
    const siblings = catalog.filter(
      (candidate) => candidate.category === component.category,
    );
    const index = siblings.findIndex(
      (candidate) => candidate.pageSlug === component.pageSlug,
    );
    const related =
      index < 0
        ? []
        : [
            ...siblings.slice(Math.max(0, index - 2), index),
            ...siblings.slice(index + 1, index + 3),
          ];
    pages.push({
      fileName: `${component.pageSlug}.mdx`,
      content: componentPage(component, related),
    });
  }
  return pages;
}

export async function generateUiDocs(): Promise<UiComponent[]> {
  const catalog = await buildUiCatalog();
  await rm(COMPONENTS_ROOT, { recursive: true, force: true });
  await mkdir(COMPONENTS_ROOT, { recursive: true });
  await mkdir(path.dirname(PREVIEW_MODULES_SOURCE), { recursive: true });
  await writeGeneratedFile(
    PREVIEW_MODULES_SOURCE,
    previewModulesSource(catalog),
  );
  await writeGeneratedFile(
    PREVIEW_METADATA_SOURCE,
    previewMetadataSource(catalog),
  );
  for (const page of renderUiDocsPages(catalog)) {
    await writeFile(path.join(COMPONENTS_ROOT, page.fileName), page.content);
  }
  return catalog;
}
