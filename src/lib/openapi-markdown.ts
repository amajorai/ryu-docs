/**
 * Markdown projection of one generated OpenAPI operation or webhook page.
 *
 * A generated operation page's MDX body is only a `Layout` that renders
 * `<APIPage document="…" operations={[…]} />` (a webhook page passes
 * `webhooks={[…]}` instead), so its processed Markdown holds no path,
 * parameters, body schema, or responses. `getLLMText` uses this module
 * to append a compact summary rendered from the same vendored spec, so the
 * `.md` projection, `llms.mdx`, and `llms-full.txt` describe the operation.
 *
 * Pure functions over `unknown` input: the spec is read through type guards,
 * never asserted, and every local `$ref` is resolved with a depth limit.
 */

export interface OperationReference {
  /** The schema id the page passes to `APIPage`, such as `./specs/services/mail.json`. */
  document: string;
  operations: { method: string; path: string }[];
  /** Entries of the spec's top-level `webhooks` map, present only on webhook pages. */
  webhooks?: { method: string; name: string }[];
}

type JsonRecord = Record<string, unknown>;

const HTTP_METHODS = new Set([
  "get",
  "put",
  "post",
  "delete",
  "options",
  "head",
  "patch",
  "trace",
]);

/** The most `$ref` hops followed for one value, so a cyclic spec cannot loop. */
const MAX_REF_DEPTH = 16;

/** The longest example printed, in characters, before it is cut. */
const MAX_EXAMPLE_CHARS = 4000;

function isRecord(value: unknown): value is JsonRecord {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function stringField(record: JsonRecord, key: string): string | undefined {
  const value = record[key];
  return typeof value === "string" ? value : undefined;
}

/** Table cells must stay on one line and must not open a new column. */
function cell(text: string): string {
  return text.replace(/\s+/g, " ").replace(/\|/g, "\\|").trim();
}

function operationEntry(value: unknown): { method: string; path: string }[] {
  if (!isRecord(value)) {
    return [];
  }
  const path = stringField(value, "path");
  const method = stringField(value, "method");
  return path && method ? [{ method, path }] : [];
}

function webhookEntry(value: unknown): { method: string; name: string }[] {
  if (!isRecord(value)) {
    return [];
  }
  const name = stringField(value, "name");
  const method = stringField(value, "method");
  return name && method ? [{ method, name }] : [];
}

const DOCUMENT_PROP = /\bdocument="([^"]+)"/;

const ARRAY_PROPS = {
  operations: /\boperations=\{(\[.*?\])\}/s,
  webhooks: /\bwebhooks=\{(\[.*?\])\}/s,
} as const;

/** The parsed JSON array of one `prop={[…]}` attribute, or `[]`. */
function arrayProp(raw: string, prop: keyof typeof ARRAY_PROPS): unknown[] {
  const source = ARRAY_PROPS[prop].exec(raw)?.[1];
  if (!source) {
    return [];
  }
  try {
    const parsed: unknown = JSON.parse(source);
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

const GENERATED_COMMENT =
  /^\{\/\*\s*This file was generated by Fumadocs\.[\s\S]*?\*\/\}[ \t]*$/gm;
const GENERATED_LAYOUT =
  /^export default function Layout\(props\) \{$[\s\S]*?^\}[ \t]*$/gm;

/**
 * Removes the generator's scaffolding from a generated OpenAPI page's
 * Markdown: the "generated by Fumadocs" comment and the `Layout` ESM block
 * that renders `APIPage`. Prose around them is kept. Agents reading the
 * `.md`, `/llms.mdx`, and `llms-full.txt` projections get the operation
 * Markdown instead of that JavaScript.
 */
export function stripGeneratedScaffold(markdown: string): string {
  return markdown
    .replace(GENERATED_COMMENT, "")
    .replace(GENERATED_LAYOUT, "")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

/**
 * Reads the `document` and `operations` (or `webhooks`) props of the
 * generated `APIPage` call from a page's raw MDX, or `null` when the page has
 * none.
 */
export function parseOperationReference(
  raw: string,
): OperationReference | null {
  const document = DOCUMENT_PROP.exec(raw)?.[1];
  if (!document) {
    return null;
  }
  const operations = arrayProp(raw, "operations").flatMap(operationEntry);
  const webhooks = arrayProp(raw, "webhooks").flatMap(webhookEntry);
  if (webhooks.length > 0) {
    return { document, operations, webhooks };
  }
  return operations.length > 0 ? { document, operations } : null;
}

function decodePointerSegment(segment: string): string {
  return segment.replace(/~1/g, "/").replace(/~0/g, "~");
}

/** Follows local `#/…` references; anything else is returned as it is. */
function resolve(spec: JsonRecord, value: unknown): unknown {
  let current = value;
  for (let depth = 0; depth < MAX_REF_DEPTH; depth += 1) {
    if (!isRecord(current)) {
      return current;
    }
    const ref = stringField(current, "$ref");
    if (!ref?.startsWith("#/")) {
      return current;
    }
    let target: unknown = spec;
    for (const segment of ref.slice(2).split("/")) {
      target = isRecord(target)
        ? target[decodePointerSegment(segment)]
        : undefined;
    }
    current = target;
  }
  return current;
}

function refName(value: unknown): string | undefined {
  if (!isRecord(value)) {
    return;
  }
  const ref = stringField(value, "$ref");
  return ref?.split("/").at(-1);
}

/** A short type label such as `string`, `MailMessage`, or `array of string`. */
function typeLabel(spec: JsonRecord, schema: unknown, depth = 0): string {
  const name = refName(schema);
  if (name) {
    return name;
  }
  if (!isRecord(schema) || depth > 4) {
    return "any";
  }
  const variants = schema.anyOf ?? schema.oneOf;
  if (Array.isArray(variants)) {
    return variants
      .map((variant) => typeLabel(spec, variant, depth + 1))
      .join(" | ");
  }
  if (Array.isArray(schema.enum)) {
    return schema.enum.map((entry) => JSON.stringify(entry)).join(" | ");
  }
  const type = schema.type;
  const base = Array.isArray(type)
    ? type.filter((entry) => typeof entry === "string").join(" | ")
    : typeof type === "string"
      ? type
      : "";
  if (base === "array") {
    return `array of ${typeLabel(spec, schema.items, depth + 1)}`;
  }
  if (base) {
    return base;
  }
  if (isRecord(schema.properties)) {
    return "object";
  }
  return "any";
}

function exampleOf(media: JsonRecord): unknown {
  if (media.example !== undefined) {
    return media.example;
  }
  if (isRecord(media.examples)) {
    for (const entry of Object.values(media.examples)) {
      if (isRecord(entry) && entry.value !== undefined) {
        return entry.value;
      }
    }
  }
  return;
}

function jsonBlock(value: unknown): string[] {
  let text = JSON.stringify(value, null, 2) ?? "null";
  if (text.length > MAX_EXAMPLE_CHARS) {
    text = `${text.slice(0, MAX_EXAMPLE_CHARS)}\n…`;
  }
  return ["```json", text, "```"];
}

/** Drops one trailing period, so joined clauses do not read `.; `. */
function withoutFinalPeriod(text: string): string {
  const trimmed = text.trim();
  return trimmed.endsWith(".") ? trimmed.slice(0, -1) : trimmed;
}

function serverLines(spec: JsonRecord, operation: JsonRecord): string[] {
  const servers = Array.isArray(operation.servers)
    ? operation.servers
    : spec.servers;
  if (!Array.isArray(servers)) {
    return [];
  }
  const lines = servers.filter(isRecord).flatMap((server) => {
    const url = stringField(server, "url");
    if (!url) {
      return [];
    }
    const variables = isRecord(server.variables) ? server.variables : {};
    const variableParts = Object.entries(variables).flatMap(
      ([name, variable]) => {
        if (!isRecord(variable)) {
          return [];
        }
        const fallback = stringField(variable, "default");
        const about = stringField(variable, "description");
        if (!(fallback || about)) {
          return [];
        }
        const label = fallback ? `${name} (default \`${fallback}\`)` : name;
        return [about ? `${label}: ${withoutFinalPeriod(about)}` : label];
      },
    );
    const description = stringField(server, "description");
    const suffix = [
      description ? withoutFinalPeriod(description) : undefined,
      ...variableParts,
    ]
      .filter(Boolean)
      .join("; ");
    return [`- \`${url}\`${suffix ? `: ${cell(suffix)}` : ""}`];
  });
  return lines.length > 0 ? ["Servers:", "", ...lines, ""] : [];
}

function securityLabel(spec: JsonRecord, name: string): string {
  const schemes = isRecord(spec.components)
    ? spec.components.securitySchemes
    : undefined;
  const scheme = isRecord(schemes) ? resolve(spec, schemes[name]) : undefined;
  if (!isRecord(scheme)) {
    return `\`${name}\``;
  }
  const type = stringField(scheme, "type");
  if (type === "apiKey") {
    const where = stringField(scheme, "in") ?? "header";
    const header = stringField(scheme, "name") ?? name;
    return `\`${name}\` (\`${header}\` ${where})`;
  }
  if (type === "http") {
    const httpScheme = stringField(scheme, "scheme") ?? "bearer";
    return `\`${name}\` (HTTP ${httpScheme})`;
  }
  return `\`${name}\` (${type ?? "custom"})`;
}

function authenticationLines(
  spec: JsonRecord,
  operation: JsonRecord,
): string[] {
  const security = Array.isArray(operation.security)
    ? operation.security
    : spec.security;
  const names = Array.isArray(security)
    ? [
        ...new Set(
          security.filter(isRecord).flatMap((entry) => Object.keys(entry)),
        ),
      ]
    : [];
  const scope = stringField(operation, "x-ryu-api-key-scope");
  const lines: string[] = [];
  if (names.length > 0) {
    lines.push(
      `Authentication (any one): ${names.map((name) => securityLabel(spec, name)).join(", ")}`,
    );
  } else if (Array.isArray(security)) {
    lines.push("Authentication: none");
  }
  if (scope) {
    lines.push(`API key scope: \`${scope}\``);
  }
  return lines.length > 0 ? [...lines, ""] : [];
}

function parameterLines(
  spec: JsonRecord,
  pathItem: JsonRecord,
  operation: JsonRecord,
): string[] {
  const all = [
    ...(Array.isArray(pathItem.parameters) ? pathItem.parameters : []),
    ...(Array.isArray(operation.parameters) ? operation.parameters : []),
  ];
  const rows = new Map<string, string>();
  for (const entry of all) {
    const parameter = resolve(spec, entry);
    if (!isRecord(parameter)) {
      continue;
    }
    const name = stringField(parameter, "name");
    const where = stringField(parameter, "in");
    if (!(name && where)) {
      continue;
    }
    const required = parameter.required === true ? "yes" : "no";
    const type = typeLabel(spec, parameter.schema);
    const description = stringField(parameter, "description") ?? "";
    // Operation-level parameters override path-level ones with the same name and location.
    rows.set(
      `${where}:${name}`,
      `| \`${name}\` | ${where} | ${required} | ${cell(type)} | ${cell(description)} |`,
    );
  }
  if (rows.size === 0) {
    return [];
  }
  return [
    "### Parameters",
    "",
    "| Name | In | Required | Type | Description |",
    "|---|---|---|---|---|",
    ...rows.values(),
    "",
  ];
}

function propertyRows(spec: JsonRecord, schema: unknown): string[] {
  const resolved = resolve(spec, schema);
  if (!isRecord(resolved)) {
    return [];
  }
  const parts = Array.isArray(resolved.allOf)
    ? resolved.allOf.map((part) => resolve(spec, part))
    : [resolved];
  const rows: string[] = [];
  for (const part of parts) {
    if (!(isRecord(part) && isRecord(part.properties))) {
      continue;
    }
    const required = new Set(
      Array.isArray(part.required)
        ? part.required.filter((entry) => typeof entry === "string")
        : [],
    );
    for (const [name, property] of Object.entries(part.properties)) {
      const target = resolve(spec, property);
      const description = isRecord(target)
        ? (stringField(target, "description") ?? "")
        : "";
      rows.push(
        `| \`${name}\` | ${cell(typeLabel(spec, property))} | ${required.has(name) ? "yes" : "no"} | ${cell(description)} |`,
      );
    }
  }
  return rows;
}

function requestBodyLines(spec: JsonRecord, operation: JsonRecord): string[] {
  const body = resolve(spec, operation.requestBody);
  if (!(isRecord(body) && isRecord(body.content))) {
    return [];
  }
  const lines = ["### Request body", ""];
  for (const [contentType, value] of Object.entries(body.content)) {
    const media = resolve(spec, value);
    if (!isRecord(media)) {
      continue;
    }
    const required = body.required === true ? "required" : "optional";
    lines.push(
      `Content type \`${contentType}\` (${required}), schema \`${cell(typeLabel(spec, media.schema))}\`.`,
      "",
    );
    const rows = propertyRows(spec, media.schema);
    if (rows.length > 0) {
      lines.push(
        "| Field | Type | Required | Description |",
        "|---|---|---|---|",
        ...rows,
        "",
      );
    }
    const example = exampleOf(media);
    if (example !== undefined) {
      lines.push("Example:", "", ...jsonBlock(example), "");
    }
  }
  return lines;
}

function responseLines(spec: JsonRecord, operation: JsonRecord): string[] {
  if (!isRecord(operation.responses)) {
    return [];
  }
  const rows: string[] = [];
  let example: { status: string; value: unknown } | undefined;
  for (const [status, value] of Object.entries(operation.responses)) {
    const response = resolve(spec, value);
    if (!isRecord(response)) {
      continue;
    }
    const description = stringField(response, "description") ?? "";
    const content = isRecord(response.content) ? response.content : {};
    const schemas = Object.values(content)
      .map((media) => resolve(spec, media))
      .filter(isRecord);
    const schema = schemas[0]?.schema;
    const type = schema === undefined ? "" : typeLabel(spec, schema);
    rows.push(
      `| \`${status}\` | ${cell(type ? `\`${type}\`` : "")} | ${cell(description)} |`,
    );
    if (!example && status.startsWith("2")) {
      for (const media of schemas) {
        const value = exampleOf(media);
        if (value !== undefined) {
          example = { status, value };
          break;
        }
      }
    }
  }
  if (rows.length === 0) {
    return [];
  }
  const lines = [
    "### Responses",
    "",
    "| Status | Body | Description |",
    "|---|---|---|",
    ...rows,
    "",
  ];
  if (example) {
    lines.push(
      `Example \`${example.status}\` response:`,
      "",
      ...jsonBlock(example.value),
      "",
    );
  }
  return lines;
}

/**
 * Renders one operation of `spec` as Markdown, or `null` when the spec has no
 * such path and method.
 */
export function renderOperationMarkdown(
  spec: unknown,
  method: string,
  path: string,
): string | null {
  const lowerMethod = method.toLowerCase();
  if (
    !(isRecord(spec) && isRecord(spec.paths) && HTTP_METHODS.has(lowerMethod))
  ) {
    return null;
  }
  const pathItem = resolve(spec, spec.paths[path]);
  if (!isRecord(pathItem)) {
    return null;
  }
  const operation = resolve(spec, pathItem[lowerMethod]);
  if (!isRecord(operation)) {
    return null;
  }
  return renderOperationBody(spec, {
    heading: `## ${lowerMethod.toUpperCase()} ${path}`,
    operation,
    pathItem,
    webhook: false,
  });
}

/**
 * Renders one entry of the spec's top-level `webhooks` map (a request the
 * service sends to your endpoint) as Markdown, or `null` when the spec has no
 * such webhook and method.
 */
export function renderWebhookMarkdown(
  spec: unknown,
  method: string,
  name: string,
): string | null {
  const lowerMethod = method.toLowerCase();
  if (
    !(
      isRecord(spec) &&
      isRecord(spec.webhooks) &&
      HTTP_METHODS.has(lowerMethod)
    )
  ) {
    return null;
  }
  const pathItem = resolve(spec, spec.webhooks[name]);
  if (!isRecord(pathItem)) {
    return null;
  }
  const operation = resolve(spec, pathItem[lowerMethod]);
  if (!isRecord(operation)) {
    return null;
  }
  return renderOperationBody(spec, {
    heading: `## Webhook: ${lowerMethod.toUpperCase()} ${name}`,
    operation,
    pathItem,
    webhook: true,
  });
}

function renderOperationBody(
  spec: JsonRecord,
  {
    heading,
    operation,
    pathItem,
    webhook,
  }: {
    heading: string;
    operation: JsonRecord;
    pathItem: JsonRecord;
    webhook: boolean;
  },
): string {
  const lines = [heading, ""];
  if (webhook) {
    lines.push(
      "Direction: the service sends this request to the endpoint you registered. When the delivery is signed, verify the signature headers against the raw body before trusting it. Answer any 2xx to acknowledge it; answer 401 when verification fails. Any other status or a timeout counts as a failed attempt.",
      "",
    );
  }
  const operationId = stringField(operation, "operationId");
  if (operationId) {
    lines.push(`Operation ID: \`${operationId}\``);
  }
  const summary = stringField(operation, "summary");
  if (summary) {
    lines.push(`Summary: ${summary}`);
  }
  if (operation.deprecated === true) {
    lines.push("Deprecated: yes");
  }
  lines.push("");
  const description = stringField(operation, "description");
  if (description) {
    lines.push(description.trim(), "");
  }
  // A webhook has no service server or API key: it arrives at your endpoint.
  lines.push(
    ...(webhook ? [] : serverLines(spec, operation)),
    ...(webhook ? [] : authenticationLines(spec, operation)),
    ...parameterLines(spec, pathItem, operation),
    ...requestBodyLines(spec, operation),
    ...responseLines(spec, operation),
  );
  return lines
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

/**
 * Renders every operation and webhook a page references, skipping those the
 * spec lacks.
 */
export function renderOperationReferenceMarkdown(
  spec: unknown,
  reference: OperationReference,
): string {
  const operations = reference.operations.map((operation) =>
    renderOperationMarkdown(spec, operation.method, operation.path),
  );
  const webhooks = (reference.webhooks ?? []).map((webhook) =>
    renderWebhookMarkdown(spec, webhook.method, webhook.name),
  );
  return [...operations, ...webhooks]
    .filter((markdown): markdown is string => Boolean(markdown))
    .join("\n\n");
}
